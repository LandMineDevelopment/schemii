    scenario text NOT NULL,
    source_revision text NOT NULL,
    fixture_digest char(64) NOT NULL CHECK (fixture_digest ~ '^[0-9a-f]{64}$'),
    workspace_id text NOT NULL CHECK (workspace_id ~ '^ws_[0-9a-f]{32}$'),
    reset_at timestamp with time zone NOT NULL DEFAULT clock_timestamp()
);

