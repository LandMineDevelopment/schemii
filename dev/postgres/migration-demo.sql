    'Launcher-owned provenance for the isolated Schemii demo database.';

CREATE TABLE public.teams (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL UNIQUE,
    slug varchar(80) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9-]+$'),
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
    email varchar(255) NOT NULL UNIQUE,
    display_name varchar(120) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    preferences jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE public.projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    name varchar(160) NOT NULL,
    code varchar(12) NOT NULL,
    visibility public.project_visibility NOT NULL DEFAULT 'team',
    budget numeric(12,2) CHECK (budget >= 0),
    starts_on date,
    ends_on date,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    UNIQUE (team_id, code),
    CHECK (ends_on IS NULL OR starts_on IS NULL OR ends_on >= starts_on)
);

CREATE TABLE public.tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    assignee_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
    parent_task_id bigint REFERENCES public.tasks(id) ON DELETE SET NULL,
    title varchar(240) NOT NULL,
    description text,
    status public.task_status NOT NULL DEFAULT 'backlog',
    priority smallint NOT NULL DEFAULT 3 CHECK (priority BETWEEN 1 AND 5),
    estimate_hours numeric(7,2) CHECK (estimate_hours >= 0),
    due_at timestamp with time zone,
    completed_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CHECK ((status = 'done') = (completed_at IS NOT NULL))
);

CREATE TABLE public.task_comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
    author_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    body text NOT NULL CHECK (length(body) > 0),
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    edited_at timestamp with time zone
);

CREATE TABLE public.tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
    name varchar(50) NOT NULL,
    color char(7) NOT NULL DEFAULT '#8b5cf6' CHECK (color ~ '^#[0-9a-fA-F]{6}$'),
    UNIQUE (team_id, name)
);

CREATE TABLE public.task_tags (
    task_id bigint NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
    tag_id bigint NOT NULL REFERENCES public.tags(id) ON DELETE CASCADE,
    PRIMARY KEY (task_id, tag_id)
);

-- Intentionally empty. Saved demo scenarios use this relation to prove that
-- PostgreSQL can accept a new required column without inventing population
-- data, while populated relations remain protected by migration planning.
CREATE TABLE public.empty_migration_lab (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label varchar(40) NOT NULL
);

-- A deliberately isolated write target for the SQL Console demo. Resetting the
-- fixture restores this row, so commit and rollback exercises are repeatable.
CREATE TABLE public.console_demo_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_key varchar(80) NOT NULL UNIQUE,
    note text NOT NULL,
    change_count integer NOT NULL DEFAULT 0 CHECK (change_count >= 0),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

