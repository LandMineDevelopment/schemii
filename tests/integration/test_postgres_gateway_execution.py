def test_incremental_cancel_rolls_back_and_restores_owned_admission(
    gateway_target: GatewayTarget, postgres_metadata: PostgresMetadataHarness,
) -> None:
    from concurrent.futures import ThreadPoolExecutor
    import time
    from schemii.common.postgres.console.gateway import execute_console_statements
    from schemii.common.postgres.errors import PostgresConsoleCancelledError
    from schemii.common.query_executions.cancellation import QueryCancellationRegistry
    namespace = gateway_target.namespace
    with postgres_metadata.connection_factory() as setup:
        setup.execute(sql.SQL("CREATE TABLE {}.managed_cancel_marker (id integer)").format(sql.Identifier(namespace)))
        setup.commit()
    gateway = PsycopgPostgresGateway()
    connection = gateway._connect(gateway_target.connection, retained=True)
    registry = QueryCancellationRegistry()
    def run():
        with registry.scope("owner", "chat", "turn"):
            return execute_console_statements(connection, [
                f"INSERT INTO {namespace}.managed_cancel_marker VALUES (1)",
                "SELECT pg_sleep(30)",
            ])
    try:
        with ThreadPoolExecutor(max_workers=1) as pool:
            future = pool.submit(run)
            with postgres_metadata.connection_factory() as observer:
                observer.autocommit = True
                deadline = time.monotonic() + 3
                while time.monotonic() < deadline:
                    row = observer.execute("SELECT wait_event FROM pg_stat_activity WHERE pid = %s", (connection.info.backend_pid,)).fetchone()
                    if row and row["wait_event"] == "PgSleep":
                        break
                    time.sleep(.01)
                else:
                    pytest.fail("managed statement never entered pg_sleep")
                registry.cancel("unrelated-owner", "chat", "turn")
                assert not future.done()
                registry.cancel("owner", "chat", "turn")
                with pytest.raises(PostgresConsoleCancelledError):
                    future.result(timeout=2)
                connection.rollback()
                assert observer.execute(sql.SQL("SELECT count(*) AS count FROM {}.managed_cancel_marker").format(sql.Identifier(namespace))).fetchone()["count"] == 0
            registry.cancel("owner", "chat", "turn")
            assert execute_console_statements(connection, ["SELECT 1"])[0].rows == ((1,),)
    finally:
        connection.close()
    assert gateway._connection_capacity._total == 0
    with closing(gateway._connect(gateway_target.connection, retained=True)) as fresh:
        assert fresh.execute("SELECT 1 AS healthy").fetchone()["healthy"] == 1
    assert gateway._connection_capacity._total == 0


@pytest.mark.parametrize("export", [False, True])
def test_fixed_scalar_named_batch_remains_cancellable_and_releases_admission(
    gateway_target: GatewayTarget, postgres_metadata: PostgresMetadataHarness, export,
) -> None:
    from concurrent.futures import ThreadPoolExecutor
    import time
    from schemii.common.postgres.errors import PostgresConsoleCancelledError
    gateway = PsycopgPostgresGateway()
    session = gateway.open_console_read_session(
        gateway_target.connection, gateway_target.namespace,
        ["SELECT 1::bigint FROM pg_sleep(30)"], on_started=lambda pid: True,
        page_memory_bytes=65536,
    )
    assert session._readers[0].fixed_row_memory_bytes == 256
    try:
        with ThreadPoolExecutor(max_workers=1) as pool:
            future = pool.submit(session.export_page if export else session.page, 0, 0, 1000)
            with postgres_metadata.connection_factory() as observer:
                observer.autocommit = True
                deadline = time.monotonic() + 3
                while time.monotonic() < deadline:
                    row = observer.execute("SELECT wait_event FROM pg_stat_activity WHERE pid = %s", (session.backend_pid,)).fetchone()
                    if row and row["wait_event"] == "PgSleep":
                        break
                    time.sleep(.01)
                else:
                    pytest.fail("fixed-width fetch never entered pg_sleep")
            session.cancel()
            with pytest.raises(PostgresConsoleCancelledError):
                future.result(timeout=2)
    finally:
        session.close()
    assert gateway._connection_capacity._total == 0
    with closing(gateway._connect(gateway_target.connection, retained=True)) as fresh:
        assert fresh.execute("SELECT 1 AS healthy").fetchone()["healthy"] == 1
    assert gateway._connection_capacity._total == 0



def test_named_fixed_scalar_extremes_preserve_every_row_and_export_snapshot(gateway_target: GatewayTarget) -> None:
    import json
    gateway = PsycopgPostgresGateway()
    session = gateway.open_console_read_session(
        gateway_target.connection, gateway_target.namespace,
        ["SELECT n::bigint, '-9223372036854775808'::bigint, '-1.7976931348623157e308'::float8, 'Infinity'::float4, CASE WHEN n % 2 = 0 THEN NULL::boolean ELSE true END FROM generate_series(1, 100) AS n"],
        on_started=lambda pid: True, page_memory_bytes=4096,
    )
    try:
        for fetch in (session.page, session.export_page):
            received = []
            while len(received) < 100:
                page = fetch(0, len(received), 30)
                assert page
                assert sum(len(json.dumps(row).encode()) for row in page) <= 4096
                assert all(row[1] == -9223372036854775808 and row[2] == -1.7976931348623157e308 for row in page)
                received.extend(row[0] for row in page)
            assert received == list(range(1, 101))
            assert fetch(0, 100, 30) == ()
    finally:
        session.close()
    assert gateway._connection_capacity._total == 0


def services(source, namespace):
    profile = source.profile.model_copy(update={"owner_id": "owner"})

    class Access:
        @contextmanager
        def use(self, owner, connection_id):
            assert (owner, connection_id) == ("owner", profile.id)
            yield profile

    gateway = PsycopgPostgresGateway()
    designs = InMemoryDesignRepository()
    workspaces = InMemoryWorkspaceRepository(designs=designs)
    repository = InMemoryMigrationRepository(designs)
    service = MigrationService(
        repository=repository,
        connection_access=Access(),
        postgres=gateway,
        workspaces=workspaces,
        designs=designs,
    )
    catalog = gateway.introspect(profile, namespace)
    workspace = service.create_import_workspace(
        "owner",
        WorkspaceCreateRecord(
            name="Owned compatibility",
            connection_id=profile.id,
            connection_owner_id="owner",
            database=profile.database,
            namespace=namespace,
        ),
        import_postgres_catalog(catalog),
        profile.revision,
        catalog,
    )
    return SimpleNamespace(
        service=service,
        gateway=gateway,
        designs=designs,
        repository=repository,
        workspace=workspace,
        profile=profile,
    )


def save(f, content):
    current = f.designs.get("owner", f.workspace.id)
    return f.designs.replace(
        "owner",
        f.workspace.id,
        SchemiiDesignReplace(
            expected_design_revision=current.revision, content=content
        ),
    )


def review(f, refresh=(), allow_destructive=False):
    current = f.designs.get("owner", f.workspace.id)
    return f.service.create_plan(
        "owner",
        f.workspace.id,
        MigrationPlanCreate(
            expected_workspace_revision=f.workspace.revision,
            expected_design_revision=current.revision,
            allow_destructive=allow_destructive,
            refresh_materialized_view_ids=list(refresh),
        ),
    )


def apply(f, plan):
    execution = f.service.create_execution(
        "owner",
        plan.id,
        MigrationExecutionCreate(
            review_digest=plan.review_digest,
            confirm_destructive=plan.destructive,
            confirm_external_changes=plan.requires_external_change_acknowledgement,
            confirm_materialized_maintenance=plan.requires_materialized_maintenance_acknowledgement,
        ),
    )
    work = f.service.execution_coordinator.claim_next("owned-pg-proof")
    assert work is not None
    return execution, f.service.execution_coordinator.process(work)


def test_real_mixed_schema_proven_success_protected_unknown_and_opaque_drift_deny(
    owned_source,
):
    source = owned_source
    namespace = 'Mixed "schema"'
    q = sql.Identifier(namespace)
    with source.connect() as connection:
        connection.execute(sql.SQL("CREATE SCHEMA {}").format(q))
        connection.execute(
            sql.SQL(
                "CREATE TABLE {}.partitioned (id integer NOT NULL) PARTITION BY RANGE (id)"
            ).format(q)
        )
        connection.execute(
            sql.SQL(
                "CREATE TABLE {}.part_a PARTITION OF {}.partitioned FOR VALUES FROM (0) TO (100)"
            ).format(q, q)
        )
        connection.execute(
            sql.SQL(
                "CREATE TABLE {}.excluded (span int4range, EXCLUDE USING gist (span WITH &&))"
            ).format(q)
        )
        connection.execute(
            sql.SQL('CREATE TABLE {}.collated (label text COLLATE "C")').format(q)
        )
        connection.execute(sql.SQL("CREATE TABLE {}.ordinary (id integer)").format(q))
        connection.execute(sql.SQL("INSERT INTO {}.ordinary VALUES (1)").format(q))
    f = services(source, namespace)
    original = f.gateway.introspect(f.profile, namespace)
    assert original.fingerprint_version == 2 and original.safety.dependency_complete
    desired = f.designs.get("owner", f.workspace.id).content.model_copy(deep=True)
    table = next(item for item in desired.tables if item.name == "ordinary")
    table.columns.append(
        DesignColumn(id="column_" + "a" * 32, name="added", data_type="text")
    )
    save(f, desired)
    plan = review(f)
    assert (
        plan.apply_capable
        and plan.compatibility.operation_safe
        and not plan.compatibility.editable_complete
    )
    _, result = apply(f, plan)
    assert result.status == "succeeded" and result.sync_status == "succeeded"
    current = f.gateway.introspect(f.profile, namespace)
    assert preservation_matches(original, current, plan.compatibility)
    assert f.repository.current_baseline("owner", f.workspace.id).complete is False
    with pytest.raises(MigrationServiceError, match="incomplete"):
        f.service.preview_baseline_reset("owner", f.workspace.id)
    with source.connect() as connection:
        assert connection.execute(
            sql.SQL("SELECT id,added FROM {}.ordinary").format(q)
        ).fetchall() == [(1, None)]
    desired = f.designs.get("owner", f.workspace.id).content.model_copy(deep=True)
    next(item for item in desired.tables if item.name == "partitioned").columns[
        0
    ].nullable = True
    save(f, desired)
    protected = review(f)
    assert not protected.apply_capable and not protected.compatibility.operation_safe
    with pytest.raises(MigrationServiceError):
        apply(f, protected)
    # A changed opaque partition bound/shape must still invalidate exact drift.
    stale = current.fingerprint
    with source.connect() as connection:
        connection.execute(
            sql.SQL(
                "CREATE TABLE {}.part_b PARTITION OF {}.partitioned FOR VALUES FROM (100) TO (200)"
            ).format(q, q)
        )
    with pytest.raises(PostgresMigrationStaleError):
        f.gateway.execute_migration(
            f.profile,
            namespace,
            stale,
            ["SELECT 1;"],
            on_started=lambda *_: None,
            on_intended=lambda *_: None,
        )
    with source.connect() as connection:
        connection.execute(
            sql.SQL(
                "CREATE FUNCTION {}.dynamic_reference() RETURNS integer LANGUAGE plpgsql AS $$ BEGIN RETURN 1; END $$"
            ).format(q)
        )
